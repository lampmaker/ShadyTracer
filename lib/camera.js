// CAMERA: compact, dependency-free camera with inverse matrices and orbit-style mouse controls
/*
THIS SECTION GENERATED BY GitHub Copilot - IMPLEMENTATION GUIDE

Overview
- Purpose: Provide a tiny, framework-free camera with both Orbit and FPS modes and a stable uniforms contract for shaders.
- Outputs: Inverse View (invView), Inverse Projection (invProjection), and camera position (camPos).
- Input: Optional canvas to attach mouse/keyboard controls; projection params (fov/aspect/near/far) or orthographic dimensions; up vector; initial mode.

Quick start
    import { CAMERA } from "./lib/ORBIT.js";
    const cam = CAMERA({ canvas, aspect: width/height, fov: 60, up: [0,0,1] });
    // Push uniforms once per frame before rendering
    const CU = cam.getUniforms();
    // Pass CU.invView and CU.invProjection (and CU.camPos if needed) to your shaders.

Runtime API (all methods are synchronous)
- get(): snapshot of the current state (pos, target, up, azimuth, elevation, distance, FOV, dimensions, mode, etc.).
- set(patch): partial update. Supported keys include:
    • mode: 'orbit' | 'fps' (switches behavior and derived params)
    • azimuth, elevation, distance, target (orbit params)
    • pos, up (direct pose; compatible with both modes)
    • FOV|fov, aspect, near, far (perspective params)
    • dimensions (orthographic width/height; depth fixed internally)
- setMode('orbit'|'fps'): switches mode. When switching to orbit, derives azimuth/elevation/distance from current pos/target.
- setOrbit({ azimuth, elevation, distance, target }): sets orbit parameters and repositions pos.
- setPose({ pos, target, up }): sets pose directly.
- setPerspective({ fov, aspect, near, far }): switches to perspective and updates projection.
- setOrtho({ width, height, depth }): switches to orthographic and updates projection.
- setUp(upVec): sets up vector and rebuilds view.
- getUniforms(): ensures matrices are up to date and returns a stable uniforms object:
    {
        invView: Float32Array(16),
    invProjection: Float32Array(16), // invProj or invOrtho depending on projection mode
        camPos: [x,y,z,1],
    }
- attachControls(canvas?): attaches mouse (orbit/pan/zoom/dolly) and keyboard (WASD/Arrows/Space/Q) controls. Auto-called if 'canvas' was passed.
- mapControls(mapping): override the default input mapping. Keys are compact strings like 'move:0:', 'wheel::ctrl', 'key:KeyW:'.
- getControlVisibility(cfg): small helper to show/hide UI fields for perspective vs orthographic.

Controls (default mapping)
- Mouse: Left drag = rotate (orbit) / look (fps); Middle drag = pan; Wheel = dolly; Wheel+Ctrl = zoom FOV (persp) or ortho size; Wheel+Shift = vertical move.
- Keyboard: WASD = move/strafe; Space/Q = up/down; Arrow keys = incremental rotate.

Uniforms contract (shader side)
- Perspective: invProjection unprojects from clip space, invView transforms to world; camera origin is invView * (0,0,0,1).
- Orthographic: invProjection encodes half-extents and depth mapping so NDC maps to camera space consistently with perspective.

Integration notes
- Always call cam.getUniforms() once per frame before issuing draw calls. It no-ops unless something changed.
- On resize, update aspect via cam.set({ aspect: w/h }).
- Switching camtype should update UI visibility (e.g., show FOV for perspective, dimensions for ortho). getControlVisibility() can help.
- For Orbit mode, prefer setOrbit() when adjusting azimuth/elevation/distance to keep the pose consistent; for FPS, use setPose()/walk.

Index usage (as in index.html)
- Instantiate with canvas + aspect + fov; call cam.set(...) from your central state (Q) once; then cam.getUniforms() each frame.
- Example shown in index.html keeps UI in sync via a Proxy that forwards to cam.set and reads cam.get(). That is recommended and minimal.

Edge cases handled internally
- Up vector nearly parallel to view direction: swaps to a safe alternate up to avoid degenerate bases.
- First-frame black output: call getUniforms() once after initial set to build inverse matrices eagerly.
*/







// THIS SECTION GENERATED BY GitHub Copilot - ULTRA COMPACT CAMERA

export function CAMERA({ canvas, aspect = 1, fov = 60, near = 0.01, far = 4000, up = [0, 1, 0], mode = 'orbit', onChange = () => { } } = {}) {
    // ---- tiny math toolkit + state + matrices - THIS SECTION GENERATED BY GitHub Copilot ----
    const v = (x = 0, y = 0, z = 0) => [x, y, z], add = (a, b, s = 1) => [a[0] + b[0] * s, a[1] + b[1] * s, a[2] + b[2] * s],
        sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]], cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]],
        len = a => Math.hypot(a[0], a[1], a[2]), norm = a => { const L = len(a) || 1; return [a[0] / L, a[1] / L, a[2] / L] },
        scl = (a, s) => [a[0] * s, a[1] * s, a[2] * s], RAD = Math.PI / 180, S = 0.0005;

    let target = v(), azimuth = 0, elevation = 90, distance = 80, pos = [0, distance, 0], upv = [...up], persp = true,
        orthoDims = [10, 10, 1000], projParams = { fov, aspect, near, far }, dirty = { view: true, proj: true },
    invView = new Array(16), invProj = new Array(16), invOrtho = new Array(16),
    invViewProj = new Array(16),
    cachedUniforms = { invView, invProjection: invProj, invViewProjection: invViewProj, camPos: [0, 0, 0, 1] },
        cachedBasis = { x: [1, 0, 0], y: [0, 1, 0], z: [0, 0, 1], dirty: true };
    /* THE LENS (0.43.0): its diameter and the distance it is focused at, in the scene's units like the pose. An
       aperture of 0 is the pinhole every picture had before; a focus of 0 is focused on the target, so an orbit stays
       sharp where it looks. A perspective camera's only: an orthographic one ignores both (getControlVisibility). */
    let lens = { aperture: 0, focus: 0 };


    // ---- unified helpers - THIS SECTION GENERATED BY GitHub Copilot ----
    const rebuild = (view = dirty.view, proj = dirty.proj, notify = true) => { if (view) buildInvView(); if (proj) (persp ? buildInvProj : buildInvOrtho)(); notify && onChange(); };
    const markDirty = (view = true, proj = false, basis = true) => { dirty.view = view; dirty.proj = proj; cachedBasis.dirty = basis; };
    const buildInvView = () => dirty.view && (() => {
        const z = norm(sub(pos, target));
        // THIS SECTION GENERATED BY GitHub Copilot - avoid degenerate basis when up is nearly parallel to view
        let xv = cross(upv, z); const Lx = len(xv);
        if (Lx < 1e-6) { const altUp = Math.abs(z[2]) < 0.9 ? [0, 0, 1] : [1, 0, 0]; xv = cross(altUp, z); }
        const x = norm(xv), y = cross(z, x);
        [invView[0], invView[1], invView[2], invView[4], invView[5], invView[6], invView[8], invView[9], invView[10]] = [...x, ...y, ...z];
        [invView[12], invView[13], invView[14]] = pos; invView[3] = invView[7] = invView[11] = 0; invView[15] = 1; dirty.view = false;
    })();

    const buildInvProj = () => dirty.proj && persp && (() => {
        const { fov, aspect: a, near: n, far: f } = projParams, t = Math.tan(fov * RAD / 2),
        k = (n - f) / (2 * f * n), b = (f + n) / (2 * f * n); invProj.splice(0, 16, a * t, 0, 0, 0, 0, t, 0, 0, 0, 0, 0, k, 0, 0, -1, b); dirty.proj = false;
    })();
    const buildInvOrtho = () => dirty.proj && !persp && (() => {
        const [w, h, d] = orthoDims;
        // Map clip z in [-1,1] to camera z in [0,-d] via camZ = -(d/2)*(clipZ+1): scale -d/2 and translate -d/2 in z
        invOrtho.splice(0, 16,
            w / 2, 0, 0, 0,
            0, h / 2, 0, 0,
            0, 0, -d / 2, 0,
            0, 0, -d / 2, 1
        );
        dirty.proj = false;
    })();
    const syncOrbitPose = () => {
        const az = azimuth * RAD, el = (90 - elevation) * RAD, c = Math.cos(el), s = Math.sin(el);
        pos = add(target, [distance * c * Math.cos(az), distance * c * Math.sin(az), distance * s]);
        // THIS SECTION GENERATED BY GitHub Copilot - preserve proj-dirty on initial sync so invProjection is built once
        dirty.view = true; cachedBasis.dirty = true; rebuild(true, dirty.proj);
    };
    const basis = () => cachedBasis.dirty ? (() => {
        const z = norm(sub(pos, target)), x = norm(cross(upv, z)), y = cross(z, x);
        return Object.assign(cachedBasis, { x, y, z, dirty: false });
    })() : cachedBasis;

    // ---- small mat4 tools (column-major) - THIS SECTION GENERATED BY GitHub Copilot ----
    const mul4 = (A, B, out) => {
        // C = A * B, all 4x4 in column-major (indices: col*4 + row)
        for (let c = 0; c < 4; c++) {
            const b0 = B[c * 4 + 0], b1 = B[c * 4 + 1], b2 = B[c * 4 + 2], b3 = B[c * 4 + 3];
            out[c * 4 + 0] = A[0] * b0 + A[4] * b1 + A[8] * b2 + A[12] * b3;
            out[c * 4 + 1] = A[1] * b0 + A[5] * b1 + A[9] * b2 + A[13] * b3;
            out[c * 4 + 2] = A[2] * b0 + A[6] * b1 + A[10] * b2 + A[14] * b3;
            out[c * 4 + 3] = A[3] * b0 + A[7] * b1 + A[11] * b2 + A[15] * b3;
        }
        return out;
    };

    // ---- public API - THIS SECTION GENERATED BY GitHub Copilot ----
    const setOrbit = ({ azimuth: a = azimuth, elevation: e = elevation, distance: d = distance, target: t = target } = {}) =>
        (azimuth = a, elevation = e, distance = d, target = [...t], mode = 'orbit', syncOrbitPose());
    const setPose = ({ pos: p, target: t, up: u = upv } = {}) => (pos = [...p], target = [...t], upv = [...u], markDirty(), rebuild());
    const setPerspective = ({ fov: F = projParams.fov, aspect: a = projParams.aspect, near: n = projParams.near, far: f = projParams.far } = {}) =>
        (projParams = { fov: F, aspect: a, near: n, far: f }, persp = true, markDirty(false, true, false), rebuild(false, true));
    const setOrtho = ({ width = orthoDims[0], height = orthoDims[1], depth = orthoDims[2] } = {}) =>
        (orthoDims = [width, height, depth], persp = false, markDirty(false, true, false), rebuild(false, true));
    const setUp = u => (upv = [...u], markDirty(), rebuild());

    // ---- controls + mouse mapping - THIS SECTION GENERATED BY GitHub Copilot ----
    const controls = {
        // THIS SECTION GENERATED BY GitHub Copilot: rotate - orbit uses az/el; fps rotates forward vector around camera position
        rotate: (dx, dy) => (mode === 'fps'
            ? (() => {
                // Rotate current forward vector around world-up (yaw) and right axis (pitch)
                const rotAxis = (v, a, ang) => {
                    const L = len(a) || 1, u = [a[0] / L, a[1] / L, a[2] / L], c = Math.cos(ang), s = Math.sin(ang), d = v[0] * u[0] + v[1] * u[1] + v[2] * u[2];
                    return [
                        v[0] * c + (u[1] * v[2] - u[2] * v[1]) * s + u[0] * d * (1 - c),
                        v[1] * c + (u[2] * v[0] - u[0] * v[2]) * s + u[1] * d * (1 - c),
                        v[2] * c + (u[0] * v[1] - u[1] * v[0]) * s + u[2] * d * (1 - c)
                    ];
                };
                let f = norm(sub(target, pos));
                const yaw = -dx * 0.2 * RAD;   // left drag positive dx yaws right, hence minus
                const pitch = -dy * 0.2 * RAD; // up drag negative dy pitches up, hence minus
                f = rotAxis(f, upv, yaw);
                const right = norm(cross(f, upv));
                f = rotAxis(f, right, pitch);
                f = norm(f); // THIS SECTION GENERATED BY GitHub Copilot: keep unit forward for stable look-at distance
                target = add(pos, f); markDirty(); rebuild();
            })()
            : (azimuth -= dx * 0.2, elevation = Math.max(0, Math.min(180, elevation - dy * 0.2)), syncOrbitPose())),
        rotateZ: dx => {
            const cos = Math.cos(dx * S), sin = Math.sin(dx * S), [ux, uy, uz] = upv;
            upv = [ux * cos - uy * sin, ux * sin + uy * cos, uz]; markDirty(); rebuild();
        },
        pan: (dx, dy) => {
            const { x, y } = basis(), dist = len(sub(pos, target)), mv = add(scl(x, dx * S * dist), scl(y, dy * S * dist));
            pos = add(pos, mv); target = add(target, mv); markDirty(); rebuild();
        },
        zoom: e => persp ? (projParams.fov = Math.max(0.1, Math.min(120, projParams.fov * (1 + e.deltaY / 1000))), markDirty(false, true, false), rebuild(false, true))
            : (orthoDims[0] *= 1 + e.deltaY / 1000, orthoDims[1] *= 1 + e.deltaY / 1000, markDirty(false, true, false), rebuild(false, true)),
        // THIS SECTION GENERATED BY GitHub Copilot - keep orbit paramization consistent when dollying
        dolly: e => {
            const amt = e.deltaY / 1000 * len(sub(pos, target));
            if (mode === 'orbit') { distance = Math.max(0.01, distance + amt); syncOrbitPose(); }  // 1 cm in a metre scene (pathtracer/params.js CAM_FIELDS)
            else { pos = add(pos, scl(basis().z, amt)); markDirty(); rebuild(); }
        },
        height: e => { const amt = -e.deltaY / 500; pos = add(pos, scl(upv, amt)); target = add(target, scl(upv, amt)); markDirty(); rebuild(); },
        // THIS SECTION GENERATED BY GitHub Copilot: walk movement along camera basis (fps or orbit-compatible)
        walk: (f = 0, r = 0, u = 0, speed = 0.5) => {
            const { x, y, z } = basis();
            // Note: z points from target->pos, so forward is -z
            const mv = add(add(scl(x, r * speed), scl(y, u * speed)), scl(z, -f * speed)); pos = add(pos, mv); target = add(target, mv); markDirty(); rebuild();
        }
    };
    // THIS SECTION GENERATED BY GitHub Copilot: replaceable mapping for inputs
    let map = {
        'move:0:': e => controls.rotate(e.dx, e.dy),
        'move:0:ctrl': e => controls.rotateZ(e.dx),
        'move:1:': e => controls.pan(-e.dx, e.dy),
        'wheel::ctrl': e => controls.zoom(e),
        'wheel::shift': e => controls.height(e),
        'wheel::': e => controls.dolly(e),
        // THIS SECTION GENERATED BY GitHub Copilot - keyboard defaults (work in both modes)
        'key:KeyW:': e => (mode === 'fps' ? controls.walk(.2,0, 0, (e.shiftKey ? 1.0 : 0.5) * (e.ctrlKey ? 0.5 : 1)) : controls.dolly({ deltaY: -100 })),
        'key:KeyS:': e => (mode === 'fps' ? controls.walk(-.2, 0, 0, (e.shiftKey ? 1.0 : 0.5) * (e.ctrlKey ? 0.5 : 1)) : controls.dolly({ deltaY: 100 })),
        'key:KeyA:': e => (mode === 'fps' ? controls.walk(0, -.2, 0, (e.shiftKey ? 1.0 : 0.5) * (e.ctrlKey ? 0.5 : 1)) : controls.pan(-50, 0)),
        'key:KeyD:': e => (mode === 'fps' ? controls.walk(0, .2, 0, (e.shiftKey ? 1.0 : 0.5) * (e.ctrlKey ? 0.5 : 1)) : controls.pan(50, 0)),
        'key:Space:': e => controls.walk(0, 0, 1, (e.shiftKey ? 1.0 : 0.5) * (e.ctrlKey ? 0.5 : 1)),
        'key:KeyQ:': e => controls.walk(0, 0, -1, (e.shiftKey ? 1.0 : 0.5) * (e.ctrlKey ? 0.5 : 1)),
        'key:ArrowLeft:': _ => controls.rotate(-5, 0),
        'key:ArrowRight:': _ => controls.rotate(5, 0),
        'key:ArrowUp:': _ => controls.rotate(0, -5),
        'key:ArrowDown:': _ => controls.rotate(0, 5)
    };
    const action = e => {
        const mod = e.ctrlKey ? 'ctrl' : e.shiftKey ? 'shift' : e.altKey ? 'alt' : '';
        const key = e.type === 'key' ? `key:${e.code}:${mod}` : `${e.dz ? 'wheel' : 'move'}:${e.btn}:${mod}`;
        return map[key]?.(e);
    };

    // THIS SECTION GENERATED BY GitHub Copilot: robust drag handling (mouseup outside canvas)
    const attachControls = (el = canvas) => el && (() => {
        let x = 0, y = 0, down = 0, btn = 0;
        const normEvt = (e, dx, dy, dz, b) => { (e.dx = dx, e.dy = dy, e.dz = dz, e.btn = b, x = e.clientX, y = e.clientY, action(e)); };
        const onMove = e => down && normEvt(e, e.clientX - x, e.clientY - y, 0, btn);
        const onUp = e => { down = 0; removeEventListener('mousemove', onMove); removeEventListener('mouseup', onUp); };
        const onDown = e => { down = 1; btn = e.button; x = e.clientX; y = e.clientY; addEventListener('mousemove', onMove, { passive: false }); addEventListener('mouseup', onUp, { passive: false }); };
        const onWheel = e => (e.preventDefault(), normEvt(e, 0, 0, e.deltaY, down ? btn : ''));
        // THIS SECTION GENERATED BY GitHub Copilot - keyboard controls; ignore when typing in inputs
        const isTyping = t => t && (t.tagName === 'INPUT' || t.tagName === 'TEXTAREA' || t.isContentEditable);
        const onKey = e => {
            if (isTyping(e.target)) return; if (['ArrowUp', 'ArrowDown', 'ArrowLeft', 'ArrowRight', 'Space'].includes(e.code)) e.preventDefault();
            // THIS SECTION GENERATED BY GitHub Copilot - don't mutate native Event; send a lightweight key event object
            action({ type: 'key', code: e.code, ctrlKey: e.ctrlKey, shiftKey: e.shiftKey, altKey: e.altKey });
        };
        el.addEventListener('mousedown', onDown, { passive: false });
        el.addEventListener('wheel', onWheel, { passive: false });
        addEventListener('keydown', onKey, { passive: false, capture: true });
        return () => { el.removeEventListener('mousedown', onDown); el.removeEventListener('wheel', onWheel); removeEventListener('mousemove', onMove); removeEventListener('mouseup', onUp); };
    })();

    // ---- lightweight state API - THIS SECTION GENERATED BY GitHub Copilot ----
    // get(): returns current camera state (alias of getState), set(patch): apply subset and rebuild minimal
    const get = () => getState();
    const set = (p = {}) => {
        let v = 0, pr = 0, orb = 0;
        if ('mode' in p && p.mode !== mode) { setMode(p.mode); return; }
        if ('azimuth' in p) { azimuth = p.azimuth; orb = 1; }
        if ('elevation' in p) { elevation = p.elevation; orb = 1; }
        if ('distance' in p) { distance = p.distance; orb = 1; }
        if ('target' in p) { target = [...p.target]; orb = 1; }
        if ('pos' in p) { pos = [...p.pos]; v = 1; }
        if ('up' in p) { upv = [...(p.up)]; v = 1; }
        /* THE LENS: no pose and no projection, but the picture changes -- onChange, which restarts it. Before the orbit's
           early return below, which would otherwise skip it when both come in one patch. */
        let ln = 0;
        if ('aperture' in p && Number.isFinite(+p.aperture)) { lens.aperture = Math.max(0, +p.aperture); ln = 1; }
        if ('focus' in p && Number.isFinite(+p.focus)) { lens.focus = Math.max(0, +p.focus); ln = 1; }
        if ('camtype' in p) {
            const toOrtho = (p.camtype === 1);
            persp = (p.camtype === 0);
            pr = 1;
            // If switching to orthographic, ensure width reflects current aspect
            if (toOrtho) {
                const h = orthoDims[1];
                const a = projParams.aspect || 1;
                orthoDims[0] = h * a;
            }
        }
      if ('dimensions' in p) {
            // 'dimensions' is the orthographic WIDTH (orthoDims[0]); the height is it over the aspect. (This said
            // height until 2026-10-02 while the code below made it the width: builder/pointedit.js planeView fits by it.)
            const h = p.dimensions;
            const a = projParams.aspect || 1;
            orthoDims = [h, h/a, orthoDims[2]];
            pr = 1;
        }
  
        // Accept both 'fov' and legacy 'FOV'
        if ('fov' in p) { projParams.fov = p.fov; pr = 1; }
        else if ('FOV' in p) { projParams.fov = p.FOV; pr = 1; }
        if ('aspect' in p) { projParams.aspect = p.aspect; pr = 1; }
        if ('near' in p) { projParams.near = p.near; pr = 1; }
        if ('far' in p) { projParams.far = p.far; pr = 1; }
        // If both orbit and projection changed, ensure both view and projection get rebuilt
        if (pr) dirty.proj = true; // ensure projection actually rebuilds this call
        if (orb && mode === 'orbit') { syncOrbitPose(); if (pr) rebuild(false, true); return; }
        if (v || pr) return rebuild(v, pr);
        if (ln) onChange();
    };
    const setMode = m => {
        if (m === 'orbit') {
            const d = sub(pos, target), L = len(d) || 1; distance = L; azimuth = Math.atan2(d[1], d[0]) / RAD; elevation = Math.acos(d[2] / L) / RAD;
        }
        mode = m; rebuild(true, false);
    };
    const mapControls = m => (map = m || map);

    // ---- exports + sync - THIS SECTION GENERATED BY GitHub Copilot ----
    syncOrbitPose(); canvas && attachControls(canvas); // init
    const getUniforms = () => (
        rebuild(dirty.view, dirty.proj, false),
        // Select projection inverse matrix and compute invViewProjection = invView * invProjection
        (cachedUniforms.invProjection = (persp ? invProj : invOrtho)),
        mul4(invView, cachedUniforms.invProjection, invViewProj),
        (cachedUniforms.invViewProjection = invViewProj),
        [cachedUniforms.camPos[0], cachedUniforms.camPos[1], cachedUniforms.camPos[2], cachedUniforms.camPos[3]] = [...pos, 1],
        /* the lens as the kernels read it (lib/pathtracer/core/genrays.js): its RADIUS, the distance in focus (the
           target's, for a focus of 0), both in the scene's units -- a pinhole (radius 0) for an orthographic camera */
        (cachedUniforms.camLens = [persp ? lens.aperture / 2 : 0, lens.focus > 0 ? lens.focus : (len(sub(pos, target)) || 1), 0, 0]),
        cachedUniforms);
    const getState = () => ({
        // THIS SECTION GENERATED BY GitHub Copilot - expose UI-friendly aliases
        pos: [...pos], target: [...target], up: [...upv],
        azimuth, elevation, distance,
        // projection params
        ...projParams,
        fov: projParams.fov,                 // alias for UI key
        camtype: (persp ? 0 : 1),            // 0=Perspective, 1=Orthogonal (state only; not sent to shaders)
        dimensions: orthoDims[0],            // alias for UI key
        mode,
        aperture: lens.aperture, focus: lens.focus,
        orthoDims: [...orthoDims]
    });
    const getControlVisibility = (config) => {
        // (focallength and aperture were here too, for depth-of-field controls no page had: gone in 0.22.6, and the lens
        // came back as aperture and focus in 0.43.0)
        const persp = config.camtype === 0;
        return { dimensions: !persp, fov: persp, aperture: persp, focus: persp };
    };

    const resize = (a) => {
        if (typeof a === 'number' && isFinite(a) && a > 0) {
            projParams.aspect = a;
            // Keep orthographic width in sync with aspect (height stays user-controlled)
            if (!persp) { orthoDims[0] = orthoDims[1] * a; }
            markDirty(false, true, false);
            rebuild(false, true);
        }
    };
    return { get, set, setMode, mapControls, setOrbit, setPose, setPerspective, setOrtho, setUp, attachControls, getUniforms, resize, getState, getControlVisibility };
}
