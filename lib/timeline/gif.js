//======================================================================================================================
// GIF.JS — an animated GIF writer, streaming. Browsers decode GIF but none will encode one
// (WebCodecs has no GIF codec, convertToBlob ignores 'image/gif'), so the format is written here.
//
//   let g = makeGif({ width, height, fps, loop, dither, write })
//                              write(Uint8Array) receives the bytes in order (may return a promise,
//                              which is awaited); omit it and the writer collects them for finish()
//   await g.frame(rgba, i)     one frame: RGBA bytes, width x height, i the frame index from 0
//   await g.finish()           the trailer; returns the Blob when collecting
//
// EVERY FRAME HAS ITS OWN 256 COLOURS. A global palette would be chosen from the first frame and
// a scene that changes colour later would band; a local one costs 768 bytes a frame, nothing next
// to the picture. The palette is a median cut over a 5-bit-per-channel histogram, each colour the
// mean of what fell in its box. 256 colours cannot hold a path tracer's soft gradients without
// visible steps, so Floyd-Steinberg dithering is on unless `dither: false`.
//
// THE CLOCK IS IN HUNDREDTHS OF A SECOND. A frame's delay is whole centiseconds, so 30 fps (3.33)
// cannot be stored: frame i starts at round(100 i / fps) and runs until the next frame starts, so
// the delays alternate 3, 3, 4 and the film keeps time. Browsers play a delay below 2 cs as 10 cs,
// so above 50 fps a frame that would start less than 2 cs after the one before it is dropped rather
// than slowing the whole film to a crawl. A frame's delay sits in front of its picture, so each
// frame is held until the next one says when it starts.
//
// THIS SECTION GENERATED BY CLAUDE
//======================================================================================================================

// ---- palette: median cut over a 15-bit histogram ---------------------------------------------------------------------

let bin = (r, g, b) => ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3)

/** Up to `max` colours for the RGBA pixels: { palette: Uint8Array(3 n), n }. */
export let quantize = (rgba, max = 256) => {
    let count = new Float64Array(32768), sum = new Float64Array(32768 * 3)
    for (let p = 0; p < rgba.length; p += 4) {
        let r = rgba[p], g = rgba[p + 1], b = rgba[p + 2], k = bin(r, g, b)
        count[k]++; sum[3 * k] += r; sum[3 * k + 1] += g; sum[3 * k + 2] += b
    }
    let used = []
    for (let k = 0; k < 32768; k++) if (count[k]) used.push(k)
    // a box is a list of bins; its error is the pixel-weighted variance, summed over the channels
    let comp = (k, c) => c == 0 ? (k >> 10) & 31 : c == 1 ? (k >> 5) & 31 : k & 31
    let measure = bins => {
        let n = 0, m = [0, 0, 0], q = [0, 0, 0]
        for (let k of bins) {
            let w = count[k]; n += w
            for (let c = 0; c < 3; c++) { let v = comp(k, c); m[c] += w * v; q[c] += w * v * v }
        }
        let vr = m.map((s, c) => q[c] - s * s / n)
        let axis = vr[0] >= vr[1] && vr[0] >= vr[2] ? 0 : vr[1] >= vr[2] ? 1 : 2
        return { bins, n, err: vr[0] + vr[1] + vr[2], axis }
    }
    let boxes = [measure(used)]
    while (boxes.length < max) {
        let best = -1
        for (let j = 0; j < boxes.length; j++)
            if (boxes[j].bins.length > 1 && (best < 0 || boxes[j].err > boxes[best].err)) best = j
        if (best < 0 || boxes[best].err <= 0) break           // every box one colour: nothing left to split
        let { bins, n, axis } = boxes[best]
        bins.sort((a, b) => comp(a, axis) - comp(b, axis))
        // split at the weighted median, keeping both halves non-empty
        let acc = 0, cut = 1
        for (let j = 0; j < bins.length - 1; j++) { acc += count[bins[j]]; cut = j + 1; if (acc >= n / 2) break }
        boxes.splice(best, 1, measure(bins.slice(0, cut)), measure(bins.slice(cut)))
    }
    let palette = new Uint8Array(3 * boxes.length)
    boxes.forEach((bx, j) => {
        let s = [0, 0, 0]
        for (let k of bx.bins) for (let c = 0; c < 3; c++) s[c] += sum[3 * k + c]
        for (let c = 0; c < 3; c++) palette[3 * j + c] = Math.round(s[c] / bx.n)
    })
    return { palette, n: boxes.length }
}

/** The palette index of every pixel, nearest colour per 15-bit bin, dithered or not. */
export let mapPixels = (rgba, width, height, palette, n, dither = true) => {
    let lut = new Int16Array(32768).fill(-1)
    let nearest = (r, g, b) => {
        let k = bin(r, g, b)
        if (lut[k] >= 0) return lut[k]
        // the bin's centre, so the answer does not depend on which pixel asked first
        let cr = ((k >> 10) << 3) + 4, cg = (((k >> 5) & 31) << 3) + 4, cb = ((k & 31) << 3) + 4
        let bi = 0, bd = Infinity
        for (let j = 0; j < n; j++) {
            let dr = palette[3 * j] - cr, dg = palette[3 * j + 1] - cg, db = palette[3 * j + 2] - cb
            let d = 2 * dr * dr + 4 * dg * dg + 3 * db * db           // the eye weighs green most
            if (d < bd) { bd = d; bi = j }
        }
        return lut[k] = bi
    }
    let out = new Uint8Array(width * height)
    if (!dither) {
        for (let i = 0, p = 0; i < out.length; i++, p += 4) out[i] = nearest(rgba[p], rgba[p + 1], rgba[p + 2])
        return out
    }
    // Floyd-Steinberg, serpentine: the error of this row and the next, three channels each
    let cur = new Float32Array((width + 2) * 3), nxt = new Float32Array((width + 2) * 3)
    let clamp = v => v < 0 ? 0 : v > 255 ? 255 : v
    for (let y = 0; y < height; y++) {
        let ltr = (y & 1) == 0, dx = ltr ? 1 : -1
        for (let s = 0; s < width; s++) {
            let x = ltr ? s : width - 1 - s, p = 4 * (y * width + x), e = 3 * (x + 1)
            let r = clamp(rgba[p] + cur[e]), g = clamp(rgba[p + 1] + cur[e + 1]), b = clamp(rgba[p + 2] + cur[e + 2])
            let j = nearest(r | 0, g | 0, b | 0)
            out[y * width + x] = j
            let er = r - palette[3 * j], eg = g - palette[3 * j + 1], eb = b - palette[3 * j + 2]
            let ahead = e + 3 * dx, behind = e - 3 * dx
            cur[ahead] += er * 7 / 16; cur[ahead + 1] += eg * 7 / 16; cur[ahead + 2] += eb * 7 / 16
            nxt[behind] += er * 3 / 16; nxt[behind + 1] += eg * 3 / 16; nxt[behind + 2] += eb * 3 / 16
            nxt[e] += er * 5 / 16; nxt[e + 1] += eg * 5 / 16; nxt[e + 2] += eb * 5 / 16
            nxt[ahead] += er / 16; nxt[ahead + 1] += eg / 16; nxt[ahead + 2] += eb / 16
        }
        let t = cur; cur = nxt; nxt = t; nxt.fill(0)
    }
    return out
}

// ---- LZW, as GIF wants it ---------------------------------------------------------------------------------------------

/** The image data of one frame: the minimum code size byte, the LZW codes in sub-blocks, the 0 block. */
export let lzw = (indices, minCode) => {
    let bytes = [], acc = 0, nbits = 0
    let clear = 1 << minCode, eoi = clear + 1, size = minCode + 1, next = eoi + 1
    let emit = code => {
        acc |= code << nbits; nbits += size
        while (nbits >= 8) { bytes.push(acc & 255); acc >>>= 8; nbits -= 8 }
    }
    // (prefix code, next index) -> code, cleared by a generation stamp instead of a 1 M fill
    let key = new Int16Array(4096 * 256), stamp = new Int32Array(4096 * 256), gen = 1
    emit(clear)
    let prefix = indices.length ? indices[0] : 0
    for (let i = 1; i < indices.length; i++) {
        let k = indices[i], h = (prefix << 8) | k
        if (stamp[h] == gen) { prefix = key[h]; continue }
        emit(prefix)
        if (next == 4096) {                                      // the table is full: start it over
            emit(clear); gen++; size = minCode + 1; next = eoi + 1
        } else {
            // the decoder widens one code later than it adds: widen as the entry that would not fit is made
            if (next >= (1 << size)) size++
            key[h] = next++; stamp[h] = gen
        }
        prefix = k
    }
    if (indices.length) emit(prefix)
    emit(eoi)
    if (nbits > 0) bytes.push(acc & 255)
    let out = new Uint8Array(1 + bytes.length + Math.ceil(bytes.length / 255) + 1), o = 0
    out[o++] = minCode
    for (let s = 0; s < bytes.length; s += 255) {
        let m = Math.min(255, bytes.length - s)
        out[o++] = m
        for (let j = 0; j < m; j++) out[o++] = bytes[s + j]
    }
    out[o++] = 0
    return out
}

// ---- the file ---------------------------------------------------------------------------------------------------------

let u16 = v => [v & 255, (v >> 8) & 255]

export let makeGif = ({ width, height, fps = 30, loop = 0, dither = true, write = null }) => {
    if (!(width >= 1 && height >= 1 && width <= 65535 && height <= 65535)) throw Error(`a GIF cannot be ${width}x${height}`)
    let chunks = [], put = write || (b => { chunks.push(b) })
    let cs = i => Math.round(i * 100 / fps)                       // when frame i starts, in centiseconds
    let pending = null, last = -1, frames = 0

    let header = [...new TextEncoder().encode('GIF89a'), ...u16(width), ...u16(height), 0, 0, 0]
    // NETSCAPE2.0: loop `loop` times, 0 for ever; null for a GIF that plays once
    if (loop != null) header.push(0x21, 0xFF, 0x0B, ...new TextEncoder().encode('NETSCAPE2.0'), 3, 1, ...u16(loop), 0)
    let started = Promise.resolve(put(new Uint8Array(header)))

    let flush = async end => {
        if (!pending) return
        let delay = Math.min(65535, Math.max(2, end - pending.start))
        // graphic control: disposal 1 (leave it), no transparency, the delay
        await put(new Uint8Array([0x21, 0xF9, 4, 1 << 2, ...u16(delay), 0, 0]))
        await put(pending.bytes)
        pending = null; frames++
    }
    return {
        width, height,
        get frames() { return frames + (pending ? 1 : 0) },
        frame: async (rgba, i) => {
            await started
            if (rgba.length < width * height * 4) throw Error(`a frame of ${rgba.length / 4} pixels for a ${width}x${height} GIF`)
            if (i <= last) throw Error(`frame ${i} after frame ${last}`)
            last = i
            let start = cs(i)
            if (pending && start - pending.start < 2) return              // above 50 fps: the header
            await flush(start)
            let { palette, n } = quantize(rgba)
            let bits = Math.max(1, Math.ceil(Math.log2(n)))                // the table is 2^bits colours, padded
            let idx = mapPixels(rgba, width, height, palette, n, dither)
            let table = new Uint8Array(3 << bits); table.set(palette)
            let desc = [0x2C, ...u16(0), ...u16(0), ...u16(width), ...u16(height), 0x80 | (bits - 1)]
            let data = lzw(idx, Math.max(2, bits))
            let bytes = new Uint8Array(desc.length + table.length + data.length)
            bytes.set(desc); bytes.set(table, desc.length); bytes.set(data, desc.length + table.length)
            pending = { start, bytes }
        },
        finish: async _ => {
            await started
            await flush(cs(last + 1))
            await put(new Uint8Array([0x3B]))
            return write ? null : new Blob(chunks, { type: 'image/gif' })
        },
    }
}
