//======================================================================================================================
// RECORDER.JS — the offline frame stepper. Plays the timeline one frame at a time, letting the
// host render each frame as slowly and as cleanly as it likes (N samples of a path tracer, say),
// and hands the finished pictures to an encoder (encoders.js).
//
//   await record({
//       fps, from, to,           frame range: to is exclusive; times are (i / fps) seconds
//       samples,                 renders per frame, passed straight to render()
//       apply(t),                put the host in the state for time t (the sequencer does this
//                                through the registry)
//       render(samples),         async: render the current state; resolve when the picture is done
//       grab(),                  the picture: a canvas, OffscreenCanvas, ImageBitmap or VideoFrame
//       encoder,                 { add(source, i), finish() } — see encoders.js
//       onProgress(p),           { i, n, done, elapsed, eta } after every frame
//       signal,                  an AbortSignal; aborting finishes the file with the frames so far
//   })
//   -> whatever encoder.finish() returns (the Blob, or null when it streamed to disk)
//
// Every frame yields to the event loop, so the page stays responsive and STOP can get through.
//
// THIS SECTION GENERATED BY CLAUDE
//======================================================================================================================

let tick = _ => new Promise(r => setTimeout(r, 0))

export let record = async ({ fps = 30, from = 0, to, samples = 1, apply, render, grab, encoder, onProgress, signal }) => {
    let n = Math.max(0, to - from), t0 = performance.now(), done = 0
    for (let i = from; i < to; i++) {
        if (signal && signal.aborted) break
        apply(i / fps)
        await render(samples)
        if (signal && signal.aborted) break
        let src = await grab()
        await encoder.add(src, i - from)
        done++
        if (onProgress) {
            let elapsed = (performance.now() - t0) / 1000
            onProgress({ i: i - from, n, done, elapsed, eta: done ? elapsed / done * (n - done) : 0 })
        }
        await tick()
    }
    return encoder.finish()
}
