//======================================================================================================================
// TIMELINE.JS — the keyframe model. Pure data and maths: no DOM, no host, runs in node.
//
// A timeline is a frame rate, a duration, and a list of TRACKS. A track animates one property of
// the host (named by `prop`, which is a registry id — see registry.js) through a sorted list of
// KEYS {t, v, ease}: t in seconds, v a number or an array of numbers (a camera pose is six of
// them; every component interpolates on its own), ease an optional per-segment override.
//
// Between keys the track's `interp` decides the curve:
//   linear   straight line
//   smooth   smoothstep between the two keys (eases both ends, never overshoots) — the default
//   spline   a cardinal spline through the neighbouring keys (C1 through every key; can
//            overshoot a little, which is what makes a camera path read as one motion)
//   step     hold the value until the next key (what an enum or a switch needs)
// A key's `ease` ('in' | 'out' | 'inout' | 'linear') reshapes the segment that STARTS at it.
//
// Nothing here rounds to integers or option lists: that is the registry's job at apply time, so
// the same curve can drive a float and an integer property alike.
//
// THIS SECTION GENERATED BY CLAUDE
//======================================================================================================================

export const INTERPS = ['linear', 'smooth', 'spline', 'step']
export const EASES = ['linear', 'in', 'out', 'inout']

let clamp01 = u => u < 0 ? 0 : u > 1 ? 1 : u
let smooth = u => u * u * (3 - 2 * u)
let easeFn = {
    linear: u => u,
    in: u => u * u,
    out: u => 1 - (1 - u) * (1 - u),
    inout: smooth,
}

// componentwise helpers: a value is a number or an array of numbers
let isArr = Array.isArray
export let cloneV = v => isArr(v) ? v.slice() : v
let map2 = (a, b, f) => isArr(a) ? a.map((x, i) => f(x, isArr(b) ? b[i] : b)) : f(a, isArr(b) ? b[0] : b)
export let lerpV = (a, b, u) => map2(a, b, (x, y) => x + (y - x) * u)

/* CUBIC HERMITE on one segment with finite-difference tangents from the neighbouring keys
   (a cardinal / Catmull-Rom spline on non-uniform knots). k0..k3 are keys; k0 and k3 may be
   null at the ends, where the tangent falls back to the segment's own slope. */
let hermite = (k0, k1, k2, k3, u) => {
    let dt = k2.t - k1.t
    let slope = (a, b) => map2(b.v, a.v, (y, x) => (y - x) / Math.max(1e-9, b.t - a.t))
    let m1 = k0 ? slope(k0, k2) : slope(k1, k2)
    let m2 = k3 ? slope(k1, k3) : slope(k1, k2)
    let h00 = 2 * u ** 3 - 3 * u ** 2 + 1, h10 = u ** 3 - 2 * u ** 2 + u
    let h01 = -2 * u ** 3 + 3 * u ** 2, h11 = u ** 3 - u ** 2
    let term = (p1, t1, p2, t2) => h00 * p1 + h10 * dt * t1 + h01 * p2 + h11 * dt * t2
    return isArr(k1.v) ? k1.v.map((p1, i) => term(p1, m1[i], k2.v[i], m2[i])) : term(k1.v, m1, k2.v, m2)
}

/** The value of one track at time t, or undefined when it has no keys. */
export let valueAt = (track, t) => {
    let ks = track.keys, n = ks.length
    if (!n) return undefined
    if (t <= ks[0].t) return cloneV(ks[0].v)
    if (t >= ks[n - 1].t) return cloneV(ks[n - 1].v)
    let i = 0
    while (i < n - 2 && ks[i + 1].t <= t) i++
    let a = ks[i], b = ks[i + 1]
    if (track.interp == 'step') return cloneV(a.v)
    let u = clamp01((t - a.t) / Math.max(1e-9, b.t - a.t))
    let e = a.ease && easeFn[a.ease] ? easeFn[a.ease] : track.interp == 'smooth' ? smooth : easeFn.linear
    u = e(u)
    if (track.interp == 'spline') return hermite(ks[i - 1] || null, a, b, ks[i + 2] || null, u)
    return lerpV(a.v, b.v, u)
}

/**
 * A timeline: { fps, duration, tracks } plus the operations on it. Tracks are one per property
 * (addTrack returns the existing track when the property already has one).
 */
export let makeTimeline = ({ fps = 30, duration = 10 } = {}) => {
    let T = {
        fps, duration, tracks: [],
        frames: _ => Math.max(1, Math.round(T.duration * T.fps)),
        snap: t => Math.round(t * T.fps) / T.fps,
        track: prop => T.tracks.find(k => k.prop == prop),
        addTrack: (prop, interp = 'smooth') => {
            let k = T.track(prop)
            if (!k) { k = { prop, interp, keys: [] }; T.tracks.push(k) }
            return k
        },
        removeTrack: prop => { T.tracks = T.tracks.filter(k => k.prop != prop) },
        /** Set a key: replaces one within half a frame of t, else inserts in time order. */
        setKey: (track, t, v, ease) => {
            let tol = 0.5 / T.fps
            let k = track.keys.find(k => Math.abs(k.t - t) < tol)
            if (k) { k.v = cloneV(v); if (ease !== undefined) k.ease = ease; return k }
            k = { t, v: cloneV(v), ease: ease || null }
            track.keys.push(k)
            T.sortKeys(track)
            return k
        },
        moveKey: (track, key, t) => { key.t = Math.max(0, t); T.sortKeys(track) },
        deleteKey: (track, key) => { track.keys = track.keys.filter(k => k !== key) },
        sortKeys: track => track.keys.sort((a, b) => a.t - b.t),
        valueAt: (track, t) => valueAt(track, t),
        /** Every animated property's value at t, as { prop: value }. */
        sample: t => {
            let out = {}
            for (let k of T.tracks) { let v = valueAt(k, t); if (v !== undefined) out[k.prop] = v }
            return out
        },
        /** Last key time over all tracks, in seconds (0 when empty). */
        extent: _ => T.tracks.reduce((m, k) => k.keys.length ? Math.max(m, k.keys[k.keys.length - 1].t) : m, 0),
        toJSON: _ => ({
            fps: T.fps, duration: T.duration,
            tracks: T.tracks.map(k => ({ prop: k.prop, interp: k.interp,
                keys: k.keys.map(x => ({ t: x.t, v: cloneV(x.v), ...(x.ease ? { ease: x.ease } : {}) })) })),
        }),
        fromJSON: o => {
            if (!o) return T
            if (o.fps > 0) T.fps = +o.fps
            if (o.duration > 0) T.duration = +o.duration
            T.tracks = (o.tracks || []).map(k => ({
                prop: '' + k.prop,
                interp: INTERPS.includes(k.interp) ? k.interp : 'smooth',
                keys: (k.keys || []).filter(x => isFinite(x.t)).map(x => ({
                    t: Math.max(0, +x.t), v: cloneV(x.v), ease: EASES.includes(x.ease) ? x.ease : null,
                })).sort((a, b) => a.t - b.t),
            }))
            return T
        },
    }
    return T
}
