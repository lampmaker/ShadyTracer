//======================================================================================================================
// ZIP.JS — a stored (uncompressed) ZIP writer, streaming. PNG frames are already compressed, so
// the archive only has to hold them together for an editor or ffmpeg to pick up.
//
//   let z = makeZip(sink)      sink.write(Uint8Array) receives the bytes in order; omit it and
//                              the writer collects them for finish()
//   z.add(name, bytes)         one entry (Uint8Array), written through immediately
//   await z.finish()           central directory + end record; returns the Blob when collecting
//
// Plain 32-bit ZIP: entries and the archive stay below 4 GB (a few thousand 4K PNGs). ZIP64 is
// the obvious extension if that is ever hit.
//
// THIS SECTION GENERATED BY CLAUDE
//======================================================================================================================

let CRC = new Int32Array(256)
for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; CRC[n] = c }
export let crc32 = bytes => {
    let c = -1
    for (let i = 0; i < bytes.length; i++) c = CRC[(c ^ bytes[i]) & 255] ^ (c >>> 8)
    return (c ^ -1) >>> 0
}

let dosTime = (d = new Date()) => ({
    time: (d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1),
    date: ((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate(),
})
let u8 = s => new TextEncoder().encode(s)
let le = (...fields) => {                        // [[value, bytes], ...] little-endian
    let n = fields.reduce((s, f) => s + f[1], 0), out = new Uint8Array(n), o = 0
    for (let [v, b] of fields) for (let i = 0; i < b; i++) out[o++] = Math.floor(v / 2 ** (8 * i)) & 255
    return out
}

export let makeZip = sink => {
    let chunks = sink ? null : []
    let off = 0, entries = []
    let write = b => { if (chunks) chunks.push(b); else sink.write(b); off += b.length }
    let { time, date } = dosTime()
    return {
        add: (name, bytes) => {
            let nm = u8(name), crc = crc32(bytes), at = off
            write(le([0x04034b50, 4], [20, 2], [0x800, 2], [0, 2], [time, 2], [date, 2],
                [crc, 4], [bytes.length, 4], [bytes.length, 4], [nm.length, 2], [0, 2]))
            write(nm); write(bytes)
            entries.push({ nm, crc, size: bytes.length, at })
        },
        finish: async _ => {
            let cd = off
            for (let e of entries) {
                write(le([0x02014b50, 4], [20, 2], [20, 2], [0x800, 2], [0, 2], [time, 2], [date, 2],
                    [e.crc, 4], [e.size, 4], [e.size, 4], [e.nm.length, 2], [0, 2], [0, 2], [0, 2], [0, 2], [0, 4], [e.at, 4]))
                write(e.nm)
            }
            write(le([0x06054b50, 4], [0, 2], [0, 2], [entries.length, 2], [entries.length, 2], [off - cd, 4], [cd, 4], [0, 2]))
            return chunks ? new Blob(chunks, { type: 'application/zip' }) : null
        },
    }
}
