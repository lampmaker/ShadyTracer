//======================================================================================================================
// EXPORT-UI.JS — the library's own export menu: size, samples per frame, format, bitrate, file
// name, range, the RECORD/STOP button with its progress bar, and SAVE/LOAD for the timeline file.
// Plain inputs bound to one settings object, so a host can also drive the same object from its
// own GUI. Mounted by the sequencer in the drawer under the transport bar.
//
//   let x = makeExportUI(hostEl, settings, { record, stop, save, load, changed, canvasSize })
//   x.refresh()                 inputs <- settings
//   x.progress({ i, n, eta })   during a recording
//   x.state('idle' | 'recording' | 'done' | 'error', message)
//
// THIS SECTION GENERATED BY CLAUDE
//======================================================================================================================

import { ENCODERS } from './encoders.js'

export const SIZES = {
    '1080p  1920×1080': [1920, 1080], '4K  3840×2160': [3840, 2160], '720p  1280×720': [1280, 720],
    'square  1080×1080': [1080, 1080], 'vertical  1080×1920': [1080, 1920], 'canvas size': [0, 0],
}

let el = (tag, cls, text) => { let e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e }
let lab = (t, e, title) => { let l = el('label', 'tl-lab', t); if (title) l.title = title; l.appendChild(e); return l }
let numIn = (min, max, step, w) => { let i = el('input', 'tl-num'); i.type = 'number'; i.min = min; i.max = max; i.step = step; if (w) i.style.width = w + 'px'; return i }
let fmtEta = s => s < 90 ? `${Math.round(s)} s` : `${Math.floor(s / 60)} min ${String(Math.round(s % 60)).padStart(2, '0')} s`

export let makeExportUI = (host, S, hooks) => {
    let root = el('div', 'tl-export')
    host.appendChild(root)
    let changed = _ => { hooks.changed && hooks.changed(); refresh() }

    // row 1: the picture
    let r1 = el('div', 'tl-row')
    let sizeSel = el('select', 'tl-sel')
    for (let k in SIZES) { let o = el('option', null, k); o.value = k; sizeSel.appendChild(o) }
    let wIn = numIn(16, 8192, 2, 64), hIn = numIn(16, 8192, 2, 64), sppIn = numIn(1, 4096, 1, 56)
    sizeSel.addEventListener('change', _ => {
        let [w, h] = SIZES[sizeSel.value]
        if (!w) [w, h] = hooks.canvasSize ? hooks.canvasSize() : [S.width, S.height]
        S.width = w; S.height = h; changed()
    })
    wIn.addEventListener('change', _ => { S.width = Math.max(16, wIn.value | 0); changed() })
    hIn.addEventListener('change', _ => { S.height = Math.max(16, hIn.value | 0); changed() })
    sppIn.addEventListener('change', _ => { S.samples = Math.max(1, sppIn.value | 0); changed() })
    r1.append(lab('size', sizeSel), wIn, el('span', null, '×'), hIn,
        lab('renders / frame', sppIn, 'how many render passes (samples) each frame accumulates before it is captured'))
    // row 2: the file
    let r2 = el('div', 'tl-row')
    let fmtSel = el('select', 'tl-sel')
    for (let k in ENCODERS) { let o = el('option', null, ENCODERS[k].label + (ENCODERS[k].available() ? '' : ' (unavailable here)')); o.value = k; fmtSel.appendChild(o) }
    fmtSel.addEventListener('change', _ => { S.format = fmtSel.value; changed() })
    let brIn = numIn(1, 200, 1, 48)
    brIn.addEventListener('change', _ => { S.bitrate = Math.max(1, +brIn.value); changed() })
    let nameIn = el('input', 'tl-text'); nameIn.type = 'text'; nameIn.title = 'file name, without extension'
    nameIn.addEventListener('change', _ => { S.filename = nameIn.value.trim() || 'timeline'; changed() })
    let fromIn = numIn(0, 1e6, 0.1, 56), toIn = numIn(0, 1e6, 0.1, 56)
    fromIn.addEventListener('change', _ => { S.from = Math.max(0, +fromIn.value); changed() })
    toIn.addEventListener('change', _ => { S.to = Math.max(0, +toIn.value); changed() })
    let streamIn = el('input'); streamIn.type = 'checkbox'
    streamIn.addEventListener('change', _ => { S.stream = streamIn.checked; changed() })
    let streamLab = lab('to disk', streamIn, 'write the file straight to disk while recording (asks where first). Off: assemble in memory and download at the end')
    r2.append(lab('format', fmtSel), lab('Mbit/s', brIn, 'video bitrate (MP4 only)'), lab('name', nameIn),
        lab('from s', fromIn, 'first second to render'), lab('to s', toIn, 'last second to render; 0 = the whole duration'), streamLab)
    if (!globalThis.showSaveFilePicker) streamLab.style.display = 'none'
    // row 3: go
    let r3 = el('div', 'tl-row')
    let rec = el('button', 'tl-btn tl-rec', 'RECORD')
    rec.title = 'render every frame of the range with the renders-per-frame above and write the file'
    rec.addEventListener('click', _ => state == 'recording' ? hooks.stop() : hooks.record())
    let prog = el('div', 'tl-prog'); let fill = el('div', 'tl-prog-fill'); prog.appendChild(fill)
    let status = el('span', 'tl-status', '')
    let save = el('button', 'tl-btn', 'SAVE…'); save.title = 'save the timeline and these settings to a JSON file'
    save.addEventListener('click', _ => hooks.save())
    let load = el('button', 'tl-btn', 'LOAD…'); load.title = 'load a timeline JSON file'
    load.addEventListener('click', _ => hooks.load())
    r3.append(rec, prog, status, save, load)
    root.append(r1, r2, r3)

    let state = 'idle'
    let refresh = _ => {
        let key = Object.keys(SIZES).find(k => SIZES[k][0] == S.width && SIZES[k][1] == S.height) || 'canvas size'
        sizeSel.value = key
        wIn.value = S.width; hIn.value = S.height; sppIn.value = S.samples
        fmtSel.value = ENCODERS[S.format] ? S.format : 'png'
        brIn.value = S.bitrate; nameIn.value = S.filename
        fromIn.value = S.from; toIn.value = S.to; streamIn.checked = !!S.stream
        brIn.parentElement.style.opacity = S.format == 'mp4' ? 1 : 0.4
    }
    refresh()
    return {
        root, refresh,
        progress: ({ i, n, eta }) => {
            fill.style.width = (n ? (i + 1) / n * 100 : 0) + '%'
            status.textContent = `frame ${i + 1} / ${n}${eta > 0.5 ? `, ~${fmtEta(eta)} left` : ''}`
        },
        state: (s, msg = '') => {
            state = s
            rec.textContent = s == 'recording' ? 'STOP' : 'RECORD'
            rec.classList.toggle('tl-live', s == 'recording')
            if (s != 'recording') fill.style.width = s == 'done' ? '100%' : '0'
            status.textContent = msg
            status.classList.toggle('tl-err', s == 'error')
        },
    }
}
