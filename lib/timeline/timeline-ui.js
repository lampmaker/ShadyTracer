//======================================================================================================================
// TIMELINE-UI.JS — the editor: a transport bar, a column of track headers and a scrollable,
// zoomable lane canvas with the keys on it. Plain DOM plus one 2D canvas; styled by timeline.css.
//
//   let ui = makeTimelineUI(host, timeline, registry, { seek, changed })
//     seek(t)     the host applies the timeline at t (the sequencer does this via the registry)
//     changed()   after every edit, so the host can autosave
//
//   ui.time       the playhead, seconds       ui.seek(t)   move it (calls hooks.seek)
//   ui.play() / ui.pause() / ui.playing       ui.refresh() rebuild after the timeline was replaced
//   ui.bar        the transport bar element (the export menu adds its buttons here)
//   ui.drawer     a strip under the bar for extra panels (the export settings live there)
//
// MOUSE  wheel = zoom time about the cursor, shift+wheel or horizontal wheel = pan, drag on
//        the ruler or an empty lane = scrub, drag a key = move it (snaps to frames, alt = free),
//        double-click a lane = key the property's current value there, double-click a key = edit
//        its value and time, right-click a key = ease / delete, shift-click = extend the selection
// KEYS   space = play/pause, delete/backspace = delete selected keys, arrows = a frame, home/end
//
// THIS SECTION GENERATED BY CLAUDE
//======================================================================================================================

import { INTERPS, EASES } from './timeline.js'

const ROWH = 24, RULERH = 22, HEADW = 200, HIT = 6
const DIMCOL = ['#7fc4ff', '#ffb26b', '#8be28b', '#e58bff', '#ffe36b', '#8bf0e5']

let el = (tag, cls, text) => { let e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e }
let btn = (label, title, fn) => { let b = el('button', 'tl-btn', label); b.title = title; b.addEventListener('click', fn); return b }
let fmt = (t, fps) => {
    let f = Math.round(t * fps), s = Math.floor(f / fps), ff = f - s * fps
    return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}.${String(ff).padStart(2, '0')}`
}
let num = v => Array.isArray(v) ? v.map(x => +x.toFixed(3)).join(', ') : +(+v).toFixed(3)

export let makeTimelineUI = (host, T, R, hooks = {}) => {
    let root = el('div', 'tl')
    root.tabIndex = 0
    host.appendChild(root)
    // the grip along the top edge: drag it to make the panel taller or shorter
    let grip = el('div', 'tl-grip')
    grip.title = 'drag to resize the panel'
    grip.addEventListener('pointerdown', e => {
        let y0 = e.clientY, h0 = host.getBoundingClientRect().height
        grip.setPointerCapture(e.pointerId)
        let mv = ev => { host.style.height = Math.max(100, h0 - (ev.clientY - y0)) + 'px'; layout() }
        grip.addEventListener('pointermove', mv)
        grip.addEventListener('pointerup', _ => grip.removeEventListener('pointermove', mv), { once: true })
    })
    root.appendChild(grip)

    // ---- transport bar --------------------------------------------------------------------
    let bar = el('div', 'tl-bar')
    let bFirst = btn('⏮', 'to the start (home)', _ => seek(0))
    let bPlay = btn('▶', 'play / pause (space)', _ => playing ? pause() : play())
    let bLast = btn('⏭', 'to the end (end)', _ => seek(T.duration))
    let readout = el('span', 'tl-time', '0:00.00')
    let frameNo = el('span', 'tl-frame', 'f 0')
    let fpsIn = el('input', 'tl-num'); fpsIn.type = 'number'; fpsIn.min = 1; fpsIn.max = 240; fpsIn.step = 1; fpsIn.title = 'frames per second'
    let durIn = el('input', 'tl-num'); durIn.type = 'number'; durIn.min = 0.1; durIn.step = 0.1; durIn.title = 'duration, seconds'
    let loopIn = el('input'); loopIn.type = 'checkbox'; loopIn.title = 'loop playback'
    let addSel = el('select', 'tl-add'); addSel.title = 'add a track for a property'
    let right = el('div', 'tl-bar-right')
    fpsIn.addEventListener('change', _ => { let v = +fpsIn.value; if (v >= 1) { T.fps = Math.round(v); changed(); draw() } })
    durIn.addEventListener('change', _ => { let v = +durIn.value; if (v > 0) { T.duration = v; changed(); draw() } })
    addSel.addEventListener('change', _ => { let p = R.get(addSel.value); addSel.value = ''; if (p) addTrack(p) })
    let lab = (t, e) => { let l = el('label', 'tl-lab', t); l.appendChild(e); return l }
    bar.append(bFirst, bPlay, bLast, readout, frameNo, lab('fps', fpsIn), lab('s', durIn), lab('loop', loopIn), addSel, right)
    root.appendChild(bar)
    let drawer = el('div', 'tl-drawer')
    root.appendChild(drawer)

    // ---- body: headers + lanes ------------------------------------------------------------
    let body = el('div', 'tl-body')
    let heads = el('div', 'tl-heads')
    let lanes = el('div', 'tl-lanes')
    let cv = el('canvas')
    lanes.appendChild(cv)
    body.append(heads, lanes)
    root.appendChild(body)
    let ctx = cv.getContext('2d')
    let popup = null                                  // the one open editor / menu

    // ---- state ----------------------------------------------------------------------------
    let time = 0, playing = false, raf = 0, tprev = 0
    let view = { t0: 0, pps: 100 }                    // seconds at the left edge, pixels per second
    let sel = new Set()                               // selected keys
    let W = 10, H = 10, fitted = false
    let x = t => (t - view.t0) * view.pps
    let tAt = px => view.t0 + px / view.pps
    let rowOf = py => Math.floor((py - RULERH) / ROWH)
    let changed = _ => hooks.changed && hooks.changed()

    let fitView = _ => { view.t0 = 0; view.pps = Math.max(5, (W - 24) / Math.max(0.1, T.duration)) }
    let layout = _ => {
        let w = lanes.clientWidth, h = Math.max(lanes.clientHeight, RULERH + T.tracks.length * ROWH)
        if (w < 10) return
        let dpr = devicePixelRatio || 1
        W = w; H = RULERH + T.tracks.length * ROWH
        cv.width = Math.round(w * dpr); cv.height = Math.round(h * dpr)
        cv.style.width = w + 'px'; cv.style.height = h + 'px'
        ctx.setTransform(dpr, 0, 0, dpr, 0, 0)
        if (!fitted) { fitted = true; fitView() }
        draw()
    }
    new ResizeObserver(layout).observe(lanes)

    // ---- the picker of properties not yet tracked ------------------------------------------
    let fillAdd = _ => {
        addSel.innerHTML = ''
        let o0 = el('option', null, '+ track'); o0.value = ''; addSel.appendChild(o0)
        let groups = new Map()
        for (let p of R.list()) {
            if (T.track(p.id)) continue
            let g = p.group || ''
            if (!groups.has(g)) groups.set(g, [])
            groups.get(g).push(p)
        }
        for (let [g, ps] of groups) {
            let parent = addSel
            if (g) { parent = el('optgroup'); parent.label = g; addSel.appendChild(parent) }
            for (let p of ps) { let o = el('option', null, p.label || p.id); o.value = p.id; parent.appendChild(o) }
        }
    }

    // ---- track headers --------------------------------------------------------------------
    let rebuildHeads = _ => {
        heads.innerHTML = ''
        let top = el('div', 'tl-head-top', 'tracks')
        top.style.height = RULERH + 'px'
        heads.appendChild(top)
        for (let k of T.tracks) {
            let p = R.get(k.prop)
            let row = el('div', 'tl-head')
            row.style.height = ROWH + 'px'
            let name = el('span', 'tl-head-name', p ? (p.label || p.id) : k.prop + ' (unknown)')
            name.title = p ? `${k.prop}${p.dims > 1 ? ` (${p.dims} values)` : ''}` : 'no property of this name in this host'
            let key = btn('●', 'key the current value at the playhead', _ => keyCurrent(k))
            key.classList.add('tl-key')
            let interp = el('select', 'tl-interp')
            interp.title = 'how the value moves between keys'
            for (let i of INTERPS) { let o = el('option', null, i); o.value = i; interp.appendChild(o) }
            interp.value = k.interp
            if (p && p.options) { interp.value = 'step'; interp.disabled = true }
            interp.addEventListener('change', _ => { k.interp = interp.value; changed(); draw() })
            let del = btn('✕', 'remove this track', _ => { T.removeTrack(k.prop); k.keys.forEach(x => sel.delete(x)); changed(); refresh() })
            del.classList.add('tl-del')
            row.append(name, key, interp, del)
            heads.appendChild(row)
        }
        fillAdd()
    }

    // ---- drawing --------------------------------------------------------------------------
    let tickStep = _ => {
        let steps = [1 / T.fps, 0.1, 0.25, 0.5, 1, 2, 5, 10, 15, 30, 60, 120, 300]
        for (let s of steps) if (s * view.pps >= 70) return s
        return steps[steps.length - 1]
    }
    let rangeOf = (k, p, d) => {
        // the vertical range a lane's curve is drawn against: the property's, else the keys'
        let r = p && R.range(p)
        if (r) return r
        let lo = Infinity, hi = -Infinity
        for (let key of k.keys) { let v = Array.isArray(key.v) ? key.v[d] : key.v; lo = Math.min(lo, v); hi = Math.max(hi, v) }
        if (!(hi > lo)) { lo -= 1; hi += 1 }
        let pad = (hi - lo) * 0.1
        return [lo - pad, hi + pad]
    }
    let draw = _ => {
        if (W < 10) return
        let Hc = cv.clientHeight
        ctx.clearRect(0, 0, W, Hc)
        ctx.fillStyle = '#2b2b2b'; ctx.fillRect(0, 0, W, Hc)
        // lanes
        T.tracks.forEach((k, i) => {
            ctx.fillStyle = i & 1 ? '#303030' : '#343434'
            ctx.fillRect(0, RULERH + i * ROWH, W, ROWH)
        })
        // beyond the duration
        let xe = x(T.duration)
        if (xe < W) { ctx.fillStyle = 'rgba(0,0,0,0.35)'; ctx.fillRect(Math.max(0, xe), 0, W - xe, Hc) }
        // frame ticks when they are far enough apart to mean anything
        let fpx = view.pps / T.fps
        if (fpx >= 6) {
            ctx.strokeStyle = 'rgba(255,255,255,0.06)'; ctx.beginPath()
            let f0 = Math.max(0, Math.floor(tAt(0) * T.fps))
            for (let f = f0; ; f++) { let px = x(f / T.fps); if (px > W) break; ctx.moveTo(px + 0.5, RULERH - 4); ctx.lineTo(px + 0.5, Hc) }
            ctx.stroke()
        }
        // ruler
        ctx.fillStyle = '#222'; ctx.fillRect(0, 0, W, RULERH)
        let st = tickStep(), t0 = Math.max(0, Math.floor(tAt(0) / st) * st)
        ctx.font = '11px Arial, sans-serif'; ctx.textBaseline = 'top'
        for (let t = t0; ; t += st) {
            let px = x(t)
            if (px > W) break
            ctx.strokeStyle = '#666'; ctx.beginPath(); ctx.moveTo(px + 0.5, RULERH - 8); ctx.lineTo(px + 0.5, Hc); ctx.stroke()
            ctx.fillStyle = '#aaa'; ctx.fillText(st >= 1 ? fmt(t, T.fps).slice(0, -3) : t.toFixed(2) + 's', px + 3, 3)
        }
        // curves and keys
        T.tracks.forEach((k, i) => {
            let p = R.get(k.prop), y0 = RULERH + i * ROWH, dims = p ? p.dims : (Array.isArray(k.keys[0]?.v) ? k.keys[0].v.length : 1)
            if (k.keys.length > 1) {
                for (let d = 0; d < Math.min(dims, DIMCOL.length); d++) {
                    let [lo, hi] = rangeOf(k, p, d)
                    ctx.strokeStyle = DIMCOL[d]; ctx.globalAlpha = 0.5; ctx.lineWidth = 1; ctx.beginPath()
                    let px0 = Math.max(0, x(k.keys[0].t)), px1 = Math.min(W, x(k.keys[k.keys.length - 1].t))
                    for (let px = px0; px <= px1; px += 2) {
                        let v = T.valueAt(k, tAt(px)); v = Array.isArray(v) ? v[d] : v
                        let py = y0 + ROWH - 3 - (ROWH - 6) * Math.max(0, Math.min(1, (v - lo) / (hi - lo)))
                        px == px0 ? ctx.moveTo(px, py) : ctx.lineTo(px, py)
                    }
                    ctx.stroke(); ctx.globalAlpha = 1
                }
            }
            for (let key of k.keys) {
                let px = x(key.t), py = y0 + ROWH / 2
                if (px < -HIT || px > W + HIT) continue
                ctx.beginPath()
                ctx.moveTo(px, py - 6); ctx.lineTo(px + 6, py); ctx.lineTo(px, py + 6); ctx.lineTo(px - 6, py); ctx.closePath()
                ctx.fillStyle = sel.has(key) ? '#d6e1ff' : '#8fa4d6'
                ctx.fill()
                if (key.ease) { ctx.fillStyle = '#222'; ctx.beginPath(); ctx.arc(px, py, 2, 0, 7); ctx.fill() }
            }
        })
        // playhead
        let px = x(time)
        if (px >= 0 && px <= W) {
            ctx.strokeStyle = '#ff7043'; ctx.lineWidth = 1.5; ctx.beginPath(); ctx.moveTo(px, 0); ctx.lineTo(px, Hc); ctx.stroke()
            ctx.fillStyle = '#ff7043'; ctx.beginPath(); ctx.moveTo(px - 6, 0); ctx.lineTo(px + 6, 0); ctx.lineTo(px, 9); ctx.closePath(); ctx.fill()
        }
        readout.textContent = fmt(time, T.fps)
        frameNo.textContent = 'f ' + Math.round(time * T.fps)
        fpsIn.value = T.fps; durIn.value = +T.duration.toFixed(2)
    }

    // ---- editing ---------------------------------------------------------------------------
    let seek = t => {
        time = Math.max(0, Math.min(T.duration, t))
        hooks.seek && hooks.seek(time)
        draw()
    }
    let keyCurrent = k => { T.setKey(k, T.snap(time), R.current(k.prop)); changed(); draw() }
    let addTrack = p => { let k = T.addTrack(p.id, p.interp || 'smooth'); keyCurrent(k); refresh() }
    let keyAt = (px, py) => {
        let r = rowOf(py), k = T.tracks[r]
        if (!k) return null
        let best = null, bd = HIT + 1
        for (let key of k.keys) { let d = Math.abs(x(key.t) - px); if (d < bd) { bd = d; best = key } }
        return best ? { track: k, key: best } : null
    }
    let deleteSelected = _ => {
        if (!sel.size) return
        for (let k of T.tracks) k.keys = k.keys.filter(key => !sel.has(key))
        sel.clear(); changed(); draw()
    }
    let closePopup = _ => { if (popup) { popup.remove(); popup = null } }
    let openPopup = (px, py) => {
        closePopup()
        popup = el('div', 'tl-popup')
        popup.style.left = Math.min(px, W - 240) + HEADW + 'px'
        popup.style.top = py + bar.offsetHeight + drawer.offsetHeight + 'px'
        popup.addEventListener('pointerdown', e => e.stopPropagation())
        root.appendChild(popup)
        return popup
    }
    let editKey = (k, key, px, py) => {
        let p = R.get(k.prop), v = Array.isArray(key.v) ? key.v : [key.v]
        let pop = openPopup(px, py)
        let tIn = el('input', 'tl-num'); tIn.type = 'number'; tIn.step = 1 / T.fps; tIn.value = +key.t.toFixed(4)
        pop.appendChild(lab('t (s)', tIn))
        let ins = v.map((c, d) => {
            let i = el('input', 'tl-num'); i.type = 'number'; i.step = p && p.step ? p.step : 'any'; i.value = +(+c).toFixed(4)
            pop.appendChild(lab(v.length > 1 ? `v${d + 1}` : 'value', i)); return i
        })
        let ok = btn('ok', 'apply (enter)', _ => {
            let nv = ins.map(i => +i.value)
            key.v = Array.isArray(key.v) ? nv : nv[0]
            T.moveKey(k, key, +tIn.value)
            changed(); closePopup(); draw()
        })
        pop.appendChild(ok)
        pop.addEventListener('keydown', e => { if (e.key == 'Enter') ok.click(); if (e.key == 'Escape') closePopup(); e.stopPropagation() })
        ins[0].focus(); ins[0].select()
    }
    let menuKey = (k, key, px, py) => {
        let pop = openPopup(px, py)
        pop.classList.add('tl-menu')
        for (let e of EASES) {
            let b = btn((key.ease || 'linear') == e && (e != 'linear' || key.ease) ? '• ' + e : '  ' + e, `ease ${e} out of this key`, _ => {
                key.ease = e == 'linear' ? null : e; changed(); closePopup(); draw()
            })
            pop.appendChild(b)
        }
        pop.appendChild(btn('delete', 'delete this key', _ => { sel.add(key); deleteSelected(); closePopup() }))
    }

    // ---- pointer ---------------------------------------------------------------------------
    let drag = null                                   // { mode: 'scrub'|'keys'|'pan', ... }
    let pos = e => { let r = cv.getBoundingClientRect(); return [e.clientX - r.left, e.clientY - r.top] }
    cv.addEventListener('contextmenu', e => e.preventDefault())
    cv.addEventListener('pointerdown', e => {
        root.focus({ preventScroll: true })
        closePopup()
        let [px, py] = pos(e)
        if (e.button == 1) { drag = { mode: 'pan', px, t0: view.t0 }; cv.setPointerCapture(e.pointerId); return }
        let hit = keyAt(px, py)
        if (e.button == 2) {
            if (hit) { sel.clear(); sel.add(hit.key); draw(); menuKey(hit.track, hit.key, px, py) }
            return
        }
        if (hit) {
            if (e.shiftKey) sel.has(hit.key) ? sel.delete(hit.key) : sel.add(hit.key)
            else if (!sel.has(hit.key)) { sel.clear(); sel.add(hit.key) }
            drag = { mode: 'keys', px, start: [...sel].map(key => [key, key.t]), moved: false }
        } else {
            if (!e.shiftKey) sel.clear()
            drag = { mode: 'scrub' }
            seek(T.snap(tAt(px)))
        }
        cv.setPointerCapture(e.pointerId)
        draw()
    })
    cv.addEventListener('pointermove', e => {
        if (!drag) return
        let [px] = pos(e)
        if (drag.mode == 'pan') { view.t0 = Math.max(0, drag.t0 - (px - drag.px) / view.pps); draw() }
        else if (drag.mode == 'scrub') seek(T.snap(tAt(px)))
        else if (drag.mode == 'keys') {
            let dt = (px - drag.px) / view.pps
            if (Math.abs(px - drag.px) > 2) drag.moved = true
            for (let [key, t] of drag.start) key.t = Math.max(0, e.altKey ? t + dt : T.snap(t + dt))
            draw()
        }
    })
    cv.addEventListener('pointerup', e => {
        if (drag && drag.mode == 'keys') {
            T.tracks.forEach(k => T.sortKeys(k))
            if (drag.moved) changed()
        }
        drag = null
    })
    cv.addEventListener('dblclick', e => {
        let [px, py] = pos(e)
        let hit = keyAt(px, py)
        if (hit) return editKey(hit.track, hit.key, px, py)
        let k = T.tracks[rowOf(py)]
        if (k) { let t = T.snap(tAt(px)); T.setKey(k, t, R.current(k.prop)); seek(t); changed() }
    })
    cv.addEventListener('wheel', e => {
        e.preventDefault()
        let [px] = pos(e)
        if (e.shiftKey || Math.abs(e.deltaX) > Math.abs(e.deltaY)) {
            view.t0 = Math.max(0, view.t0 + (e.deltaX || e.deltaY) / view.pps)
        } else {
            let tc = tAt(px)
            view.pps = Math.max(2, Math.min(20000, view.pps * Math.exp(-e.deltaY * 0.002)))
            view.t0 = Math.max(0, tc - px / view.pps)
        }
        draw()
    }, { passive: false })
    root.addEventListener('keydown', e => {
        if (e.target.tagName == 'INPUT' || e.target.tagName == 'SELECT') return
        let f = 1 / T.fps
        if (e.key == ' ') { playing ? pause() : play(); e.preventDefault() }
        else if (e.key == 'Delete' || e.key == 'Backspace') { deleteSelected(); e.preventDefault() }
        else if (e.key == 'ArrowLeft') seek(T.snap(time - f))
        else if (e.key == 'ArrowRight') seek(T.snap(time + f))
        else if (e.key == 'Home') seek(0)
        else if (e.key == 'End') seek(T.duration)
        else if (e.key == 'Escape') { closePopup(); sel.clear(); draw() }
    })
    // a press anywhere else closes the popup; the canvas closes and reopens its own, so it is
    // left out here or the menu it just opened would close under the same press
    document.addEventListener('pointerdown', e => { if (popup && !popup.contains(e.target) && e.target !== cv) closePopup() })

    // ---- playback --------------------------------------------------------------------------
    let step = now => {
        if (!playing) return
        let t = time + (now - tprev) / 1000
        tprev = now
        if (t >= T.duration) { if (loopIn.checked) t -= T.duration; else { seek(T.duration); pause(); return } }
        seek(t)
        raf = requestAnimationFrame(step)
    }
    let play = _ => {
        if (playing) return
        if (time >= T.duration - 1e-6) time = 0
        playing = true; bPlay.textContent = '⏸'; tprev = performance.now()
        raf = requestAnimationFrame(step)
    }
    let pause = _ => { playing = false; bPlay.textContent = '▶'; cancelAnimationFrame(raf) }
    let refresh = _ => { sel.clear(); rebuildHeads(); layout() }

    refresh()
    return {
        root, bar, barRight: right, drawer, canvas: cv,
        get time() { return time }, set time(t) { seek(t) },
        get playing() { return playing },
        seek, play, pause, refresh, draw, layout, fitView: _ => { fitView(); draw() },
        addTrack, keyCurrent,
        destroy: _ => { pause(); root.remove() },
    }
}
