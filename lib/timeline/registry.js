//======================================================================================================================
// REGISTRY.JS — what a host lets the timeline animate.
//
// A property is { id, label, group, get, set, min, max, step, options, dims }:
//   id       the name tracks refer to (stable across sessions: it is what the JSON file stores)
//   label    what the track header shows; group is an optional heading in the add-track picker
//   get/set  read and write the live value. For dims > 1 both speak arrays of numbers
//   min/max  the range the editor draws the curve against (optional; the keys' own range then).
//            Either may be a function, for a range that moves with the host's state
//   step     rounding applied at apply time (1 = integer)
//   options  { label: value } for an enum; such a property always holds and never interpolates
//   dims     number of components, default 1
//
// apply(values) writes a set of { id: value } through the setters, coercing each value to its
// property's range, step and option list, and returns the ids it changed — the host resets its
// render once after that, not once per property.
//
// THIS SECTION GENERATED BY CLAUDE
//======================================================================================================================

let lim = v => typeof v == 'function' ? v() : v

export let makeRegistry = () => {
    let props = new Map()
    let coerce1 = (p, v) => {
        if (!isFinite(v)) return v
        let mn = lim(p.min), mx = lim(p.max)
        if (p.options) {                                   // nearest listed value
            let best = v, bd = Infinity
            for (let o of Object.values(p.options)) { let d = Math.abs(o - v); if (d < bd) { bd = d; best = o } }
            return best
        }
        if (p.step > 0) v = Math.round(v / p.step) * p.step
        if (mn !== undefined) v = Math.max(mn, v)
        if (mx !== undefined) v = Math.min(mx, v)
        return v
    }
    let R = {
        add: p => {
            let q = { dims: 1, ...p }
            if (q.options && !q.interp) q.interp = 'step'
            props.set(q.id, q)
            return q
        },
        remove: id => props.delete(id),
        get: id => props.get(id),
        has: id => props.has(id),
        list: _ => [...props.values()],
        /** [min, max] of a property right now, or undefined where it declares none. */
        range: p => { let mn = lim(p.min), mx = lim(p.max); return mn !== undefined && mx !== undefined && mx > mn ? [mn, mx] : undefined },
        /** The live value of a property, copied. */
        current: id => { let p = props.get(id); if (!p) return undefined; let v = p.get(); return Array.isArray(v) ? v.slice() : v },
        coerce: (p, v) => Array.isArray(v) ? v.map(x => coerce1(p, x)) : coerce1(p, v),
        /** Write { id: value } through the setters; returns the ids that were known. */
        apply: values => {
            let done = []
            for (let id in values) {
                let p = props.get(id)
                if (!p) continue
                p.set(R.coerce(p, values[id]))
                done.push(id)
            }
            return done
        },
    }
    return R
}
