//======================================================================================================================
// ENCODERS.JS — where the frames go. Every encoder has the same tiny contract, so the recorder
// (recorder.js) does not care which one it feeds:
//
//   let enc = await ENCODERS.mp4.make({ width, height, fps, bitrate, sink })
//   await enc.add(source, i)      source: a canvas, OffscreenCanvas, ImageBitmap or VideoFrame;
//                                 i the frame index from 0
//   let blob = await enc.finish() the file (a Blob), or null when it streamed to a sink
//
//   mp4   H.264 in an MP4, through the browser's own encoder (WebCodecs VideoEncoder) and the
//         vendored mp4-muxer. Chromium; the codec string is negotiated per resolution
//   png   every frame a PNG, packed in a stored ZIP (zip.js). Works in every browser and is
//         what an editor or ffmpeg wants for a lossless master
//   gif   an animated GIF that loops (gif.js): 256 colours a frame, dithered, timed in
//         hundredths of a second. Works in every browser; for a small size and a short clip
//
// `sink` is optional: a FileSystemWritableFileStream from showSaveFilePicker() streams the file
// to disk as it is made (needed for long or 4K sequences); without one the file is assembled in
// memory and returned.
//
// THIS SECTION GENERATED BY CLAUDE
//======================================================================================================================

import { Muxer, ArrayBufferTarget, FileSystemWritableFileStreamTarget } from './mp4-muxer.mjs'
import { makeZip } from './zip.js'
import { makeGif } from './gif.js'

/** Trigger a browser download of a Blob. */
export let download = (blob, name) => {
    let a = document.createElement('a')
    a.href = URL.createObjectURL(blob)
    a.download = name
    a.click()
    setTimeout(_ => URL.revokeObjectURL(a.href), 30000)
}

// Codec strings in order of preference. H.264 first (plays everywhere), level 5.2 down to 4.0
// so 4K gets the level it needs where the machine offers it; then VP9 and AV1 in the same MP4
// container for browsers built without H.264 (Chromium proper, as opposed to Chrome). The
// muxer's codec name rides along. Whichever the machine's encoder accepts for this size is used.
const CODECS = [
    ['avc1.640034', 'avc'], ['avc1.640033', 'avc'], ['avc1.64002a', 'avc'], ['avc1.640028', 'avc'],
    ['avc1.4d002a', 'avc'], ['avc1.4d0028', 'avc'], ['avc1.42e028', 'avc'],
    ['vp09.00.51.08', 'vp9'], ['vp09.00.40.08', 'vp9'], ['vp09.00.10.08', 'vp9'],
    ['av01.0.12M.08', 'av1'], ['av01.0.08M.08', 'av1'], ['av01.0.04M.08', 'av1'],
]

let pickCodec = async cfg => {
    for (let [codec, mux] of CODECS) {
        try { let r = await VideoEncoder.isConfigSupported({ ...cfg, codec }); if (r.supported) return { codec, mux } } catch (_) { }
    }
    return null
}

export let mp4Encoder = async ({ width, height, fps = 30, bitrate = 12e6, sink = null }) => {
    if (!globalThis.VideoEncoder) throw Error('WebCodecs VideoEncoder is not available in this browser -- use the PNG sequence')
    width &= ~1; height &= ~1                            // H.264 wants even dimensions
    let base = { width, height, bitrate: Math.round(bitrate), framerate: fps, latencyMode: 'quality' }
    let pick = await pickCodec(base)
    if (!pick) throw Error(`no video encoder for ${width}x${height} on this machine -- use the PNG sequence`)
    let { codec, mux } = pick
    let target = sink ? new FileSystemWritableFileStreamTarget(sink) : new ArrayBufferTarget()
    let muxer = new Muxer({
        target, video: { codec: mux, width, height, frameRate: fps },
        fastStart: sink ? false : 'in-memory', firstTimestampBehavior: 'offset',
    })
    let failed = null
    let enc = new VideoEncoder({
        output: (chunk, meta) => muxer.addVideoChunk(chunk, meta),
        error: e => { failed = e },
    })
    enc.configure({ ...base, codec, ...(mux == 'avc' ? { avc: { format: 'avc' } } : {}) })
    let us = 1e6 / fps
    return {
        codec, mux, width, height,
        add: async (source, i) => {
            if (failed) throw failed
            let f = source instanceof VideoFrame ? source
                : new VideoFrame(source, { timestamp: Math.round(i * us), duration: Math.round(us) })
            // a keyframe every two seconds keeps the file seekable without bloating it
            enc.encode(f, { keyFrame: i % Math.max(1, Math.round(fps * 2)) == 0 })
            f.close()
            // back-pressure: let the encoder drain before piling more frames on it
            while (enc.encodeQueueSize > 4) await new Promise(r => enc.addEventListener('dequeue', r, { once: true }))
        },
        finish: async _ => {
            await enc.flush()
            enc.close()
            muxer.finalize()
            if (failed) throw failed
            if (sink) { await sink.close(); return null }
            return new Blob([target.buffer], { type: 'video/mp4' })
        },
        abort: async _ => { try { enc.close() } catch (_) { } if (sink) { try { await sink.close() } catch (_) { } } },
    }
}

// draw anything the recorder hands over onto a 2D canvas, so it can become a PNG
let toPng = async (source, width, height) => {
    let cv = new OffscreenCanvas(width, height)
    let x = cv.getContext('2d')
    x.drawImage(source, 0, 0, width, height)
    if (source instanceof VideoFrame) source.close()
    let blob = await cv.convertToBlob({ type: 'image/png' })
    return new Uint8Array(await blob.arrayBuffer())
}

export let pngEncoder = async ({ width, height, sink = null, prefix = 'frame' }) => {
    let zip = makeZip(sink ? { write: b => sink.write(b) } : null)
    let pending = Promise.resolve()          // writes are ordered by frame, whatever the sink does
    return {
        width, height,
        add: async (source, i) => {
            let bytes = await toPng(source, width, height)
            zip.add(`${prefix}_${String(i).padStart(5, '0')}.png`, bytes)
        },
        finish: async _ => {
            let blob = await zip.finish()
            if (sink) { await sink.close(); return null }
            return blob
        },
        abort: async _ => { if (sink) { try { await sink.close() } catch (_) { } } },
    }
}

// the RGBA pixels of anything the recorder hands over, at the GIF's size
let toRgba = (source, width, height) => {
    let cv = new OffscreenCanvas(width, height)
    let x = cv.getContext('2d', { willReadFrequently: true })
    x.drawImage(source, 0, 0, width, height)
    if (source instanceof VideoFrame) source.close()
    return x.getImageData(0, 0, width, height).data
}

export let gifEncoder = async ({ width, height, fps = 30, sink = null }) => {
    let gif = makeGif({ width, height, fps, write: sink ? b => sink.write(b) : null })
    return {
        width, height,
        add: async (source, i) => gif.frame(toRgba(source, width, height), i),
        finish: async _ => {
            let blob = await gif.finish()
            if (sink) { await sink.close(); return null }
            return blob
        },
        abort: async _ => { if (sink) { try { await sink.close() } catch (_) { } } },
    }
}

