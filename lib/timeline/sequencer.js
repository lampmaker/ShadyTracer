//======================================================================================================================
// SEQUENCER.JS — the one call that gives a page a keyframe timeline with video export.
//
//   import { makeRegistry } from './registry.js'
//   import { makeSequencer } from './sequencer.js'
//
//   let reg = makeRegistry()
//   reg.add({ id: 'x', label: 'x', min: 0, max: 800, get: _ => S.x, set: v => S.x = v })
//   let seq = makeSequencer({
//       host: document.querySelector('#panel'),  // where the timeline + its menu are mounted
//       registry: reg,
//       render: async samples => draw(samples),  // render the current state; resolve when done
//       grab: _ => canvas,                       // the finished picture (canvas / bitmap / VideoFrame)
//       onSeek: (values, t) => draw(1),          // after the registry applied time t
//       storageKey: 'myapp.timeline',            // autosave in localStorage (optional)
//   })
//
// Optional hooks: begin({ width, height, samples, fps }) before a recording starts (switch the
// renderer to the export size, stop a live loop), end() after it, onSettings(settings) when an
// export setting changed (draw an aspect guide, say). `defaults` seeds the export settings.
//
// What comes back: { timeline, settings, registry, ui, seek(t), record(), stop(), save(),
// load(obj), loadFile(), show(), hide(), toggle(), visible, recording, time, destroy() }.
//
// The timeline and the export settings persist together: in localStorage on every change (when
// storageKey is given) and as one JSON file through SAVE/LOAD:
//   { app: 'timeline', version: 1, timeline: { fps, duration, tracks }, export: { ... } }
//
// THIS SECTION GENERATED BY CLAUDE
//======================================================================================================================

import { makeTimeline } from './timeline.js'
import { makeTimelineUI } from './timeline-ui.js'
import { makeExportUI } from './export-ui.js'
import { record } from './recorder.js'
import { ENCODERS, download } from './encoders.js'

const FILEVERSION = 1

export let makeSequencer = ({ host, registry, render, grab, begin, end, onSeek, onSettings, storageKey, defaults = {} }) => {
    let T = makeTimeline(defaults.timeline || {})
    let S = {
        width: 1920, height: 1080, samples: 8, format: ENCODERS.mp4.available() ? 'mp4' : 'png',
        bitrate: 12, filename: 'timeline', from: 0, to: 0, stream: false,
        ...(defaults.export || {}),
    }
    let recording = false, ctrl = null, saveTimer = 0

    // ---- persistence ----------------------------------------------------------------------
    let fileObj = _ => ({ app: 'timeline', version: FILEVERSION, timeline: T.toJSON(), export: { ...S } })
    let load = obj => {
        if (!obj || typeof obj != 'object') return false
        T.fromJSON(obj.timeline || obj)
        if (obj.export) for (let k in S) if (k in obj.export) S[k] = obj.export[k]
        if (!ENCODERS[S.format] || !ENCODERS[S.format].available()) S.format = ENCODERS.mp4.available() ? 'mp4' : 'png'
        ui && ui.refresh(); xui && xui.refresh()
        persist(); onSettings && onSettings(S)
        return true
    }
    let persist = _ => {
        if (!storageKey) return
        clearTimeout(saveTimer)
        saveTimer = setTimeout(_ => { try { localStorage.setItem(storageKey, JSON.stringify(fileObj())) } catch (_) { } }, 300)
    }
    let changed = _ => { persist(); onSettings && onSettings(S) }
    let save = _ => download(new Blob([JSON.stringify(fileObj(), null, 1)], { type: 'application/json' }), S.filename + '.timeline.json')
    let loadFile = _ => {
        let e = document.createElement('input')
        e.type = 'file'; e.accept = '.json,application/json'
        e.addEventListener('change', _ => e.files[0] && e.files[0].text().then(t => {
            let d
            try { d = JSON.parse(t) } catch (err) { alert('not a JSON file: ' + err.message); return }
            if (!load(d)) alert('not a timeline file')
        }))
        e.click()
    }

    // ---- the state at a time -----------------------------------------------------------
    let seek = t => {
        let values = T.sample(t)
        registry.apply(values)
        onSeek && onSeek(values, t)
    }

    // ---- recording -------------------------------------------------------------------
    let stop = _ => { if (ctrl) ctrl.abort() }
    let doRecord = async _ => {
        if (recording) return
        let E = ENCODERS[S.format] || ENCODERS.png
        if (!E.available()) { xui.state('error', `${E.label} is not available in this browser`); return }
        let fps = T.fps, from = Math.round(S.from * fps), to = S.to > 0 ? Math.round(S.to * fps) : T.frames()
        if (to <= from) { xui.state('error', 'empty range'); return }
        let name = `${S.filename || 'timeline'}.${E.ext}`
        let sink = null
        if (S.stream && globalThis.showSaveFilePicker) {
            try {
                let h = await showSaveFilePicker({ suggestedName: name, types: [{ description: E.label, accept: { [E.mime]: ['.' + E.ext] } }] })
                sink = await h.createWritable()
            } catch (_) { return }                     // the picker was cancelled
        }
        recording = true; ctrl = new AbortController()
        ui.pause()
        xui.state('recording', 'starting…')
        let enc = null, blob = null
        try {
            enc = await E.make({ width: S.width, height: S.height, fps, bitrate: S.bitrate * 1e6, sink })
            if (begin) await begin({ width: enc.width, height: enc.height, samples: S.samples, fps, frames: to - from })
            blob = await record({
                fps, from, to, samples: S.samples,
                apply: t => { ui.time = t },            // moves the playhead, which seeks through the registry
                render, grab: async _ => (SEQ._lastGrab = await grab()), encoder: enc,
                onProgress: p => xui.progress(p), signal: ctrl.signal,
            })
            if (blob) download(blob, name)
            xui.state('done', ctrl.signal.aborted ? 'stopped -- the frames so far were written' : `done: ${name}`)
        } catch (err) {
            console.error(err)
            if (enc) await enc.abort()
            xui.state('error', err.message || String(err))
        } finally {
            recording = false; ctrl = null
            if (end) await end()
            seek(ui.time)                                // back to the live state at the playhead
        }
    }

    // ---- the panel ---------------------------------------------------------------------
    let ui = makeTimelineUI(host, T, registry, { seek, changed })
    let xui = makeExportUI(ui.drawer, S, {
        record: doRecord, stop, save, load: loadFile, changed,
        canvasSize: _ => { let c = grab && grab(); return c && c.width ? [c.width, c.height] : [S.width, S.height] },
    })
    let gear = document.createElement('button')
    gear.className = 'tl-btn'; gear.textContent = '⚙ export'; gear.title = 'export settings and the RECORD button'
    gear.addEventListener('click', _ => { ui.drawer.classList.toggle('open'); ui.layout() })
    ui.barRight.appendChild(gear)
    ui.drawer.classList.add('open')

    if (storageKey) { try { load(JSON.parse(localStorage.getItem(storageKey))) } catch (_) { } }
    onSettings && onSettings(S)

    let visible = true
    let SEQ = null                                   // the object returned below; _lastGrab is kept on it for tests
    let show = _ => { visible = true; host.classList.remove('tl-hidden'); ui.layout() }
    let hide = _ => { visible = false; ui.pause(); host.classList.add('tl-hidden') }
    return SEQ = {
        timeline: T, settings: S, registry, ui, exportUI: xui, _lastGrab: null,
        seek, record: doRecord, stop, save, load, loadFile,
        show, hide, toggle: _ => visible ? hide() : show(),
        get visible() { return visible }, get recording() { return recording },
        get time() { return ui.time }, set time(t) { ui.time = t },
        destroy: _ => { stop(); ui.destroy() },
    }
}
